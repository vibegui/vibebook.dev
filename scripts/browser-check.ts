// Real browser + local Worker check. Start `bun run dev --var DEV_EMAIL:codex-test@example.test`
// and run `bun scripts/browser-check.ts`. Test data is confined to a newly created local room.
import { chromium, expect as baseExpect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import {parseRoomEvent} from '../shared/validation';
import {createRoomStore} from '../svelte/roomStore';
const expect=baseExpect.configure({timeout:60_000});
const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:8797';
if(!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw Error('Browser check requires a local test Worker');
const output=process.env.TEST_OUTPUT_DIR || '/tmp/vibebook-browser-check';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-gpu']});
const errors:string[]=[];
const capturedRoom=createRoomStore();
try {
  const desktop=await browser.newContext({locale:'en-US',viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  await desktop.addCookies([{name:'vb_lang',value:'en',url:base}]);
  desktop.setDefaultTimeout(60_000);
  const created=await desktop.request.post(`${base}/api/books`,{timeout:120_000,data:{title:'Svelte migration verification'},headers:{origin:base}});
  if(!created.ok())throw Error(`Create room ${created.status()}: ${await created.text()}`);
  const {id}=await created.json() as {id:string};
  const second=await browser.newContext({locale:'pt-BR',viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  await second.addCookies([{name:'vb_lang',value:'pt',url:base}]);
  // Two independent live sessions exercise server fan-out without sending invitations.
  const a=await desktop.newPage(), b=await second.newPage();
  for(const page of [a,b]){
    page.on('websocket',socket=>{socket.on('framesent',frame=>{try{const m=JSON.parse(String(frame.payload));if(m.t==='msg')console.log('WS sent',m.text);}catch{}});socket.on('framereceived',frame=>{try{const m=JSON.parse(String(frame.payload));if(socket.url().includes('/ws/'))capturedRoom.apply(parseRoomEvent(String(frame.payload)),id);if(m.t==='msg')console.log('WS received',m.m.text);}catch{}});});
    page.on('pageerror',error=>{errors.push(error.message);console.error('BROWSER_ERROR',error.message);});
    await page.route('https://fonts.googleapis.com/**',route=>route.abort());
    await page.route('https://fonts.gstatic.com/**',route=>route.abort());
    await page.route('http://127.0.0.1:47321/**',route=>route.abort());
  }
  const opened=Date.now();
  await a.goto(`${base}/b/${id}`,{waitUntil:'domcontentloaded',timeout:120_000});
  await expect(a.locator('#composer')).toBeVisible({timeout:120_000});
  await expect(a.locator('#side #newEpic')).toBeAttached();
  const readyMs=Date.now()-opened;
  await a.locator('#newEpic input').fill('Verify live Svelte');
  await a.locator('#newEpic input').press('Enter');
  const epic=a.locator('#side [data-thread]').filter({hasText:'Verify live Svelte'});
  await expect(epic).toHaveCount(1,{timeout:90_000});
  const eid=await epic.getAttribute('data-thread');
  if(!eid)throw Error('Missing epic');
  await epic.click();
  await expect(a.locator('#newTask input')).toBeVisible({timeout:90_000});
  await a.locator('#newTask input').fill('Check two-session updates');
  await a.locator('#newTask input').press('Enter');
  await expect(a.locator('.task .tt').first()).toContainText('Check two-session updates');
  await a.locator('#newTask input').fill('Keep epic open during verification');
  await a.locator('#newTask input').press('Enter');
  await expect(a.locator('.task')).toHaveCount(2);
  console.log('PASS desktop renders; native epic and tasks created');
  await b.goto(`${base}/b/${id}?t=${eid}`,{waitUntil:'domcontentloaded',timeout:120_000});
  await expect(b.locator('#composer')).toBeVisible({timeout:120_000});
  await expect(b.locator('#tasks .tt').first()).toContainText('Check two-session updates');
  const taskId=await a.locator('[data-task]').filter({hasText:'Check two-session updates'}).getAttribute('data-task');
  if(!taskId)throw Error('Missing task id');
  const checkbox=a.locator(`[data-task="${taskId}"] input[type=checkbox]`);
  const remoteCheckbox=b.locator(`[data-task="${taskId}"] input[type=checkbox]`);
  await checkbox.check();
  await expect(remoteCheckbox).toBeChecked({timeout:90_000});
  await checkbox.uncheck();
  await expect(b.locator('#tasks input[type=checkbox]').first()).not.toBeChecked({timeout:90_000});
  // A native keyed message row preserves escaping, actions and reply context.
  await a.locator('#input').fill('Migration <img src=x onerror=alert(1)> verified');
  await a.locator('#sendBtn').click();
  await expect(b.locator('#msgs .msg .txt').filter({hasText:'Migration <img src=x onerror=alert(1)> verified'})).toHaveCount(1,{timeout:90_000});
  console.log('PASS two live sessions, task fan-out and escaped chat');
  await expect(a.locator('#msgs .txt img')).toHaveCount(0);
  const sent=a.locator('#msgs .msg').filter({hasText:'Migration <img src=x onerror=alert(1)> verified'});
  await sent.hover();await sent.locator('[data-reply]').click();
  await expect(a.locator('#replyBar')).toBeVisible();
  await a.locator('#input').fill('Reply keeps its context');
  await a.locator('#sendBtn').click();
  await expect(b.locator('#msgs .msg').filter({hasText:'Reply keeps its context'}).locator('.quote')).toContainText('Migration',{timeout:90_000});
  console.log('PASS reply context');
  // Typed HTTP upload then native files filter/viewer and shared pin update.
  await a.locator('#fileInput').setInputFiles({name:'verification.txt',mimeType:'text/plain',buffer:Buffer.from('Verified typed upload')});
  await expect(a.locator('#sendBtn')).toBeEnabled({timeout:90_000});
  await a.locator('#input').fill('Attached verification');
  await a.locator('#sendBtn').click();
  await a.locator('.ptabs [data-pane=files]').click();
  await expect(a.locator('#filesPane .ftile').filter({hasText:'verification.txt'})).toHaveCount(1,{timeout:90_000});
  console.log('PASS typed file upload');
  await a.locator('#filesPane .pinBtn').first().click();
  await expect(b.locator('.pinsSec')).toContainText('verification.txt',{timeout:90_000});
  await a.locator('.ptabs [data-pane=board]').click();
  const card=a.locator(`#kanban .kcard[data-k="${taskId}"]`);
  await expect(card).toBeVisible();
  await card.focus();await card.press('ArrowRight');
  await expect(card).toHaveAttribute('data-status','doing',{timeout:90_000});
  await a.locator('#kanban [data-mode=list]').click();
  await expect(a.locator('#kanban .krow').filter({hasText:'Check two-session updates'})).toHaveCount(1);
  await a.locator('.ptabs [data-pane=doc]').click();
  await a.locator('#inboxBtn').click();
  const inbox=a.locator('dialog[open]').filter({has:a.getByRole('heading',{name:'Inbox',exact:true})});
  await expect(inbox).toBeVisible();await inbox.getByRole('button',{name:'Close',exact:true}).click();
  console.log('PASS files/pins, board keyboard/list and Inbox');
  await a.screenshot({path:`${output}/desktop-after.png`,fullPage:true});
  await b.screenshot({path:`${output}/mobile-after.png`,fullPage:true});
  // Both CodeMirror instances edit the same Yjs document; the backend mirrors it to Book.
  await a.locator('#docEditBar').click();
  await b.locator('#docPeek [data-pane=doc]').click();
  await b.locator('#docEditBar').click();
  await expect(a.locator('#cm .cm-content')).toBeVisible();
  await expect(b.locator('#cm .cm-content')).toBeVisible();
  const docText=await a.locator('#cm .cm-content').innerText();
  await a.locator('#cm .cm-content').fill(`${docText}\n\nLive document synchronization verified`);
  await expect(b.locator('#cm .cm-content')).toContainText('Live document synchronization verified',{timeout:90_000});
  console.log('PASS two live Yjs document editors');
  const invalid=await desktop.request.post(`${base}/api/books/${id}/post`,{data:{text:42},headers:{origin:base}});
  expect(invalid.status()).toBe(400);
  expect(errors).toEqual([]);
  const snapshot=capturedRoom.get();
  if(snapshot)await writeFile(`${output}/room-state.json`,JSON.stringify({t:'state',...snapshot}));
  await writeFile(`${output}/results.json`,JSON.stringify({room:id,epic:eid,readyMs,checks:['two live sessions','task updates','escaped chat','reply context','typed upload','files and pins','board keyboard/list','invalid HTTP payload','two Yjs editors'],errors},null,2));
  console.log(`PASS real Worker/browser checks; evidence ${output}; ready ${readyMs} ms`);
}finally{await browser.close();}
