import { createHash } from "node:crypto";
import { readdir, readFile, unlink, writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { projectRoot } from "../svelte/build/clientBoundary";
import { buildBrowser } from "./browser-build";

export const APP_DOCUMENT_NONCE_PLACEHOLDER = "__VIBEBOOK_APP_DOCUMENT_NONCE__";

/** Both browser and Worker import this inert string; only the browser build compiles executable source. */
export function bootstrapModule(javascript: string): string {
  if (javascript.split(APP_DOCUMENT_NONCE_PLACEHOLDER).length !== 2)
    throw new Error(
      "App document bootstrap must contain exactly one nonce placeholder",
    );
  if (/<\/script/i.test(javascript))
    throw new Error("App document bootstrap contains a closing script tag");
  return `// Generated by scripts/build-app-document.ts; do not edit.\nexport const appDocumentBootstrap = ${JSON.stringify(javascript)};\n`;
}

/** Avoid spurious Worker/Vite reloads when the watcher starts with current artifacts. */
async function writeChanged(path: string, source: string) {
  try {
    if ((await readFile(path, "utf8")) === source) return;
  } catch (error) {
    if (!(error instanceof Error && "code" in error && error.code === "ENOENT"))
      throw error;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, source);
}

export async function buildAppDocument(
  options: {
    root?: string;
    bootstrap?: string;
    host?: string;
    module?: string;
    shell?: string;
    signal?: AbortSignal;
  } = {},
) {
  const root = options.root ?? projectRoot;
  const assertCurrent = () => options.signal?.throwIfAborted();
  assertCurrent();
  const bootstrap = await buildBrowser(
    {
      entrypoints: [
        options.bootstrap ?? join(root, "browser/app-document/bootstrap.ts"),
      ],
      format: "iife",
    },
    root,
  );
  if (bootstrap.outputs.length !== 1)
    throw new Error("App bootstrap must be one classic script");
  const bootstrapJS = await bootstrap.outputs[0]!.text();
  if (
    !/^\s*\(\(\)\s*=>\s*\{/.test(bootstrapJS) ||
    !/\}\)\(\);?\s*$/.test(bootstrapJS)
  )
    throw new Error(
      "App bootstrap must keep all lexical bindings inside an IIFE",
    );
  assertCurrent();
  await writeChanged(
    options.module ?? join(root, "shared/generated/appDocumentBootstrap.ts"),
    bootstrapModule(bootstrapJS),
  );
  const host = await buildBrowser(
    {
      entrypoints: [options.host ?? join(root, "browser/app-document/host.ts")],
    },
    root,
  );
  if (host.outputs.length !== 1)
    throw new Error("App host must be one browser module");
  const hostJS = await host.outputs[0]!.text();
  assertCurrent();
  const digest = createHash("sha256").update(hostJS).digest("hex").slice(0, 20);
  const asset = "app-document-host." + digest + ".js";
  const publicRoot = join(root, "public");
  const shellPath = options.shell ?? join(publicRoot, "app.html");
  const shell = await readFile(shellPath, "utf8");
  let imports = 0;
  const next = shell.replace(
    /\/app-document-host(?:\.[a-f0-9]{20})?\.js/g,
    () => {
      imports++;
      return "/" + asset;
    },
  );
  if (imports !== 1)
    throw new Error(
      "Vanilla shell must import its app document host exactly once",
    );
  assertCurrent();
  await writeChanged(join(publicRoot, asset), hostJS);
  assertCurrent();
  if (next !== shell) await writeFile(shellPath, next);
  assertCurrent();
  for (const file of await readdir(publicRoot))
    if (
      /^app-document-host(?:\.[a-f0-9]{20})?\.js$/.test(file) &&
      file !== asset
    )
      await unlink(join(publicRoot, file));
  return { asset, digest };
}
if (import.meta.main) await buildAppDocument();
